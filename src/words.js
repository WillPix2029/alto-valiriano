export const isHV = (t) => typeof t === 'string' && GLOSS.has(norm(t))

// Guia de pronúncia aproximado para brasileiros
export function pronounce(word) {
  let s = word.toLowerCase().replace(/[?!.,]/g, '')
  s = s.replace(/kh/g, 'rr').replace(/gh/g, 'g').replace(/rh/g, 'r').replace(/ñ/g, 'nh').replace(/q/g, 'k')
    .replace(/g(?=[eēiī])/g, 'gu').replace(/j/g, 'i').replace(/[yȳ]/g, 'ü')
    .replace(/([aeiouāēīōūü])s(?=[aeiouāēīōūü])/g, '$1ss')
    .replace(/ā/g, 'á').replace(/ē/g, 'ê').replace(/ī/g, 'í').replace(/ō/g, 'ô').replace(/ū/g, 'ú')
  return s
}
